const serviceList = document.querySelector('#treatment-list');
serviceList.innerHTML = treatments.map((item, i) => `
  <article class="treatment-item">
    <h3><button class="treatment-toggle" id="treatment-button-${i}" aria-controls="treatment-panel-${i}" aria-expanded="${i === 0}"><span class="service-number">${String(i + 1).padStart(2, '0')}</span><span class="service-name">${item.name}</span>${icon('plus')}</button></h3>
    <div class="treatment-body" id="treatment-panel-${i}" role="region" aria-labelledby="treatment-button-${i}" ${i === 0 ? '' : 'hidden'}>
      <p>${item.description}</p><button class="text-link" data-book data-treatment="${item.name}">Conversar sobre este tratamento ${icon('arrow')}</button>
      <img class="treatment-mobile-image" src="public/images/${item.image}.png" width="1448" height="1086" loading="lazy" alt="${item.alt}">
    </div>
  </article>`).join('');

const treatmentImage = document.querySelector('#treatment-image');
const buttons = [...serviceList.querySelectorAll('.treatment-toggle')];
buttons.forEach((button, index) => {
  button.addEventListener('click', () => {
    const willOpen = button.getAttribute('aria-expanded') !== 'true';
    buttons.forEach((item, i) => {
      const open = willOpen && index === i;
      item.setAttribute('aria-expanded', String(open));
      document.querySelector(`#treatment-panel-${i}`).hidden = !open;
    });
    if (willOpen) {
      const item = treatments[index];
      // The build produces responsive WebP files for this dynamic image, too.
      const extension = document.documentElement.dataset.optimized ? 'webp' : 'png';
      treatmentImage.src = `public/images/${item.image}.${extension}`;
      if (extension === 'webp') treatmentImage.srcset = [480, 800, 1200].map(size => `public/images/${item.image}-${size}.webp ${size}w`).join(', ');
      treatmentImage.alt = item.alt;
      document.querySelector('#treatment-caption').textContent = item.caption;
      document.querySelector('#treatment-count').textContent = `${String(index + 1).padStart(2, '0')} / 06`;
    }
  });
  button.addEventListener('keydown', (event) => {
    let next;
    if (event.key === 'ArrowDown') next = (index + 1) % buttons.length;
    if (event.key === 'ArrowUp') next = (index + buttons.length - 1) % buttons.length;
    if (event.key === 'Home') next = 0;
    if (event.key === 'End') next = buttons.length - 1;
    if (next !== undefined) { event.preventDefault(); buttons[next].focus(); }
  });
});

// Update images generated by JS when running the optimized production build.
if (document.documentElement.dataset.optimized) {
  serviceList.querySelectorAll('img').forEach(img => {
    const base = img.getAttribute('src').replace(/\.png$/, '');
    img.src = `${base}.webp`;
    img.srcset = [480, 800, 1200].map(size => `${base}-${size}.webp ${size}w`).join(', ');
    img.sizes = '(max-width: 767px) calc(100vw - 86px), 1px';
  });
}

const menuButton = document.querySelector('.menu-toggle');
const mobileMenu = document.querySelector('#mobile-menu');
const setMenu = (open, restoreFocus = false) => {
  menuButton.setAttribute('aria-expanded', String(open));
  menuButton.setAttribute('aria-label', open ? 'Fechar menu' : 'Abrir menu');
  mobileMenu.hidden = !open;
  if (restoreFocus) menuButton.focus();
};
menuButton.addEventListener('click', () => setMenu(mobileMenu.hidden));
mobileMenu.querySelectorAll('a').forEach(link => link.addEventListener('click', () => setMenu(false)));
document.addEventListener('keydown', event => { if (event.key === 'Escape' && !mobileMenu.hidden) setMenu(false, true); });
document.addEventListener('click', event => { if (!mobileMenu.hidden && !event.target.closest('.site-header')) setMenu(false); });
window.matchMedia('(min-width: 768px)').addEventListener('change', event => { if (event.matches) setMenu(false); });

const bookingDialog = document.querySelector('#booking-dialog');
let dialogOpener;
const openDialog = (dialog, opener) => { dialogOpener = opener; dialog.showModal(); document.body.style.overflow = 'hidden'; };
document.querySelectorAll('[data-book]').forEach(button => button.addEventListener('click', () => {
  if (config.bookingUrl) {
    try {
      const url = new URL(config.bookingUrl);
      if (url.protocol === 'https:') { window.open(url.href, '_blank', 'noopener,noreferrer'); setMenu(false); return; }
    } catch { /* Missing or invalid configuration uses the honest demo state. */ }
  }
  const treatment = document.querySelector('#booking-treatment');
  treatment.hidden = !button.dataset.treatment;
  treatment.textContent = button.dataset.treatment ? `Seu interesse: ${button.dataset.treatment}` : '';
  const wasInMobileMenu = mobileMenu.contains(button);
  setMenu(false);
  openDialog(bookingDialog, wasInMobileMenu ? menuButton : button);
}));
document.querySelector('[data-privacy]').addEventListener('click', event => openDialog(document.querySelector('#privacy-dialog'), event.currentTarget));
document.querySelectorAll('dialog').forEach(dialog => {
  dialog.querySelectorAll('[data-close]').forEach(button => button.addEventListener('click', () => dialog.close()));
  dialog.addEventListener('click', event => {
    const box = dialog.getBoundingClientRect();
    if (event.target === dialog && (event.clientX < box.left || event.clientX > box.right || event.clientY < box.top || event.clientY > box.bottom)) dialog.close();
  });
  dialog.addEventListener('close', () => { document.body.style.overflow = ''; dialogOpener?.focus(); });
});

document.querySelectorAll('[data-config]').forEach(element => {
  if (config[element.dataset.config]) { element.textContent = config[element.dataset.config]; element.hidden = false; }
});
document.querySelector('#year').textContent = new Date().getFullYear();
const header = document.querySelector('.site-header');
const updateHeader = () => header.classList.toggle('scrolled', window.scrollY > 12);
window.addEventListener('scroll', updateHeader, { passive: true }); updateHeader();

if ('IntersectionObserver' in window && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
  document.documentElement.classList.add('js-ready');
  const observer = new IntersectionObserver(entries => entries.forEach(entry => {
    if (entry.isIntersecting) { entry.target.classList.add('is-visible'); observer.unobserve(entry.target); }
  }), { threshold: 0.07 });
  document.querySelectorAll('.evaluation-copy,.evaluation-image,.difference-grid article,.clinic .section-heading,.team .section-heading,.faq-intro').forEach(element => { element.classList.add('reveal'); observer.observe(element); });
}
